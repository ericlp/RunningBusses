import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { chromium } from 'playwright';
import { readStored } from './data-fixture.mjs';
import { checkPageErrors, createCourse, prepareContext } from './setup.mjs';

const browser = await chromium.launch();
try {
  const context = await browser.newContext({ locale: 'sv-SE', viewport: { width: 360, height: 740 }, serviceWorkers: 'block' });
  await prepareContext(context);
  const page = await context.newPage();
  const checkErrors = checkPageErrors(page);
  page.on('dialog', (dialog) => dialog.accept());
  await page.goto('http://localhost:4173/');
  await createCourse(page);
  const original = await readStored(page, 'courses');
  await page.click('[aria-label="Inställningar"]');
  const downloading = page.waitForEvent('download');
  await page.click('button:text-is("Exportera")');
  const download = await downloading;
  const data = JSON.parse(readFileSync(await download.path(), 'utf8'));
  assert.deepEqual(data.courses, original);
  const upload = (value) => page.setInputFiles('.modal input[type=file]', { name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(value)) });
  await upload(data);
  const preview = page.locator('.import-preview');
  await preview.waitFor();
  assert.equal(await page.locator('[role=dialog].import-preview').count(), 1);
  assert.equal(await page.locator('.modal:not(.import-preview) .import-preview').count(), 0);
  assert.match(await preview.innerText(), /1 bana/);
  assert.equal(await preview.locator('.conflict').count(), 0);
  assert.equal(await preview.locator('.primary').count(), 1);
  assert.equal(await preview.locator('input[type=radio]').count(), 2);
  assert.match(await preview.locator('input[type=radio]:checked + span').innerText(), /Lägg till i mina banor/);
  assert.equal(await preview.locator('.choice .muted').count(), 2);
  assert.match(await preview.innerText(), /1 har du redan/);
  await preview.locator('.choice:has-text("Ersätt alla mina banor")').click();
  assert.match(await preview.innerText(), /tas bort och 1 importeras/);
  await preview.locator('.choice:has-text("Lägg till i mina banor")').click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  data.courses[0].name = 'Ändrad';
  await upload(data);
  await page.waitForSelector('.conflict');
  assert.equal(await preview.locator('button.primary').isDisabled(), true);
  await page.click('text=Använd importerad');
  assert.equal(await preview.locator('button.primary').isEnabled(), true);
  await preview.locator('.primary').click();
  await page.waitForSelector('text=Importen är klar.');
  assert.equal((await readStored(page, 'courses'))[0].name, 'Ändrad');
  assert.deepEqual((await readStored(page, 'recovery')).courses, original);
  await page.locator('.modal [aria-label="Stäng"]').click();
  await page.click('[aria-label="Inställningar"]');
  const replacement = structuredClone(data);
  replacement.courses[0].id = 'replacement';
  replacement.courses[0].name = 'Replacement';
  await upload(replacement);
  await preview.waitFor();
  await preview.locator('.choice:has-text("Ersätt alla mina banor")').click();
  await preview.locator('.primary').click();
  await page.waitForSelector('text=Importen är klar.');
  assert.deepEqual(await readStored(page, 'courses'), replacement.courses);
  assert.equal((await readStored(page, 'recovery')).courses[0].name, 'Ändrad');
  await page.locator('.modal [aria-label="Stäng"]').click();
  await page.click('[aria-label="Inställningar"]');
  await upload({ format: 'x' });
  await page.waitForSelector('.backup [role=status]');
  assert.match(await page.locator('.backup [role=status]').innerText(), /ingen säkerhetskopia/);
  assert.deepEqual(await readStored(page, 'courses'), replacement.courses);
  const recovering = page.waitForEvent('download');
  await page.click('text=Hämta kopia');
  const recovery = JSON.parse(readFileSync(await (await recovering).path(), 'utf8'));
  assert.equal(recovery.courses[0].name, 'Ändrad');
  checkErrors();
  console.log('ok  backup: exact export, conflict gating, merge, replace, recovery and invalid input');
  await context.close();
} finally { await browser.close(); }
