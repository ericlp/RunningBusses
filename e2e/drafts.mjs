import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { readStored } from './data-fixture.mjs';
import { checkPageErrors, prepareContext, waitLegs } from './setup.mjs';

const browser = await chromium.launch();
try {
  for (const width of [360, 1280]) {
    const context = await browser.newContext({ locale: 'en-GB', viewport: { width, height: 740 }, serviceWorkers: 'block' });
    await prepareContext(context);
    const page = await context.newPage();
    const checkErrors = checkPageErrors(page);
    page.on('dialog', (dialog) => dialog.accept());
    await page.goto('http://localhost:4173/');
    await page.getByRole('button', { name: 'Plan', exact: true }).click();
    await page.getByRole('button', { name: 'Create course', exact: true }).click();
    assert.equal(await page.getByRole('button', { name: /Manual leg$/ }).count(), 0, 'a manual leg cannot start a course');
    await page.locator('.sheet .list button').first().click();
    await waitLegs(page, 1);
    await page.getByRole('button', { name: /Manual leg$/ }).click();
    await page.getByRole('textbox', { name: 'Name of manual leg', exact: true }).fill('Bridge');
    await page.getByRole('textbox', { name: 'Distance in km', exact: true }).fill('-1');
    await page.locator('.field.manual').getByRole('button', { name: 'Add', exact: true }).click();
    assert.equal(await page.locator('.leg-card').count(), 1);
    assert.equal(await page.getByRole('textbox', { name: 'Distance in km', exact: true }).inputValue(), '-1');
    await page.getByRole('textbox', { name: 'Distance in km', exact: true }).fill('0,25');
    await page.locator('.field.manual').getByRole('button', { name: 'Add', exact: true }).click();
    await waitLegs(page, 2);
    assert.equal(await page.getByRole('button', { name: /Reverse direction$/ }).count(), 0, 'a trailing manual leg prevents reversal');
    await page.getByRole('button', { name: 'Close and keep the draft', exact: true }).click();
    await page.getByRole('button', { name: 'Continue draft (2 legs)', exact: true }).waitFor();
    await page.reload();
    await page.getByRole('button', { name: 'Plan', exact: true }).click();
    await page.getByRole('button', { name: 'Continue draft (2 legs)', exact: true }).click();
    await waitLegs(page, 2);
    const draft = await readStored(page, 'draft');
    assert.equal(draft.legs[1].label, 'Bridge');
    assert.equal(draft.legs[1].lengthM, 250);
    await page.getByRole('button', { name: /Manual leg$/ }).click();
    await page.getByRole('textbox', { name: 'Name of manual leg', exact: true }).fill('Unknown finish');
    await page.locator('.field.manual').getByRole('button', { name: 'Add', exact: true }).click();
    await waitLegs(page, 3);
    assert.match(await page.locator('.strip-total').innerText(), /at least/);
    await page.locator('.strip button.primary').click();
    await page.locator('.modal input').fill('Manual course');
    await page.locator('.modal button.primary').click();
    await page.waitForSelector('.course');
    const saved = await readStored(page, 'courses');
    assert.equal(saved[0].legs[2].lengthM, null);
    assert.equal(await readStored(page, 'draft'), null);
    assert.match(await page.locator('.course .total').innerText(), /at least/);
    if (await page.locator('.course-main').getAttribute('aria-pressed') !== 'true') await page.locator('.course-main').click();
    await page.getByRole('button', { name: 'Edit', exact: true }).click();
    await waitLegs(page, 3);
    await page.getByRole('button', { name: 'Undo last', exact: true }).click();
    await waitLegs(page, 2);
    await page.getByRole('button', { name: 'Close and keep the draft', exact: true }).click();
    await page.reload();
    await page.getByRole('button', { name: 'Plan', exact: true }).click();
    await page.getByRole('button', { name: 'Continue editing "Manual course"', exact: true }).click();
    await waitLegs(page, 2);
    await page.getByRole('button', { name: 'Discard changes', exact: true }).click();
    await page.getByRole('button', { name: 'Create course', exact: true }).waitFor();
    assert.deepEqual(await readStored(page, 'courses'), saved, 'discarding an edit never changes the saved course');
    assert.equal(await readStored(page, 'draft'), null);
    await page.getByRole('button', { name: 'Create course', exact: true }).click();
    await page.locator('.sheet .list button').first().click();
    await waitLegs(page, 1);
    await page.getByRole('button', { name: 'Discard draft', exact: true }).click();
    await page.getByRole('button', { name: 'Create course', exact: true }).waitFor();
    assert.equal(await readStored(page, 'draft'), null);
    checkErrors();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await context.close();
    console.log(`ok  ${width}px: manual input, unknown distance, new/edit draft persistence and discard`);
  }
} finally { await browser.close(); }
