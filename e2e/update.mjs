import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { readStored, writeStored } from './data-fixture.mjs';
import { checkPageErrors, createCourse, prepareContext } from './setup.mjs';

const browser = await chromium.launch();
try {
  const context = await browser.newContext({ locale: 'sv-SE', viewport: { width: 360, height: 740 }, serviceWorkers: 'block' });
  await prepareContext(context);
  const page = await context.newPage();
  const checkErrors = checkPageErrors(page);
  page.on('dialog', (dialog) => dialog.accept());
  await page.clock.install();
  await page.goto('http://localhost:4173/');
  await createCourse(page);
  const original = await readStored(page, 'courses');
  const older = structuredClone(original);
  older[0].legs[0].line.lengthM = 1234;
  await writeStored(page, [['courses', older]]);
  await page.reload();
  await page.getByText(/uppdaterades/).waitFor();
  assert.deepEqual((await readStored(page, 'courses'))[0].legs, original[0].legs);
  await page.clock.fastForward(6001);
  await page.click('text=Planera');
  await page.waitForSelector('.course');
  await page.click('.course-main');
  await page.click('button:has-text("Markera som genomförd")');
  await page.click('.modal button.primary');
  await page.waitForSelector('.status-Completed');
  await page.click('button:has-text("Markera som ej genomförd")');
  await page.locator('.tag:text-is("Äldre data")').waitFor();
  assert.equal((await readStored(page, 'courses'))[0].pinned, true);
  assert.equal(await page.locator('button:has-text("Uppdatera till aktuell data")').count(), 1);
  await page.clock.fastForward(8001);
  await page.click('button:has-text("Uppdatera till aktuell data")');
  await page.locator('.tag:text-is("Äldre data")').waitFor({ state: 'detached' });
  assert.equal((await readStored(page, 'courses'))[0].pinned, undefined);
  checkErrors();
  console.log('ok  update: returned snapshots, completion lock, pinning and explicit refresh');
  await context.close();
} finally { await browser.close(); }
