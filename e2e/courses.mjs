import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { chromium } from 'playwright';
import { readStored } from './data-fixture.mjs';
import { checkPageErrors, prepareContext, waitLegs } from './setup.mjs';

const browser = await chromium.launch();
try {
  for (const [name, viewport] of [['phone', { width: 360, height: 740 }], ['desktop', { width: 1280, height: 800 }]]) {
    const context = await browser.newContext({ viewport, locale: 'sv-SE', serviceWorkers: 'block' });
    await prepareContext(context);
    const page = await context.newPage();
    const checkErrors = checkPageErrors(page);
    await page.clock.install();
    await page.goto('http://localhost:4173/');
    await page.waitForSelector('.list button');
    await page.click('text=Planera');
    await page.click('text=Skapa bana');
    await page.locator('.list button').first().click();
    await waitLegs(page, 1);
    await page.locator('.list button').first().click();
    await waitLegs(page, 2);
    const drafted = await page.locator('.strip-total').innerText();
    await page.locator('.strip button.primary').click();
    await page.fill('.modal input', 'Testbana');
    await page.click('.modal .primary');
    await page.waitForSelector('.course');
    assert.equal(await page.locator('.course .total').innerText(), drafted, 'saving preserves the recomputed total');
    const saved = await readStored(page, 'courses');
    assert.equal(saved.length, 1);
    assert.equal(saved[0].legs.length, 2);
    assert.equal(new Set(saved[0].legs.map((leg) => leg.line.key)).size, 2);
    await page.reload();
    await page.click('text=Planera');
    await page.waitForSelector('.course');
    assert.deepEqual(await readStored(page, 'courses'), saved, 'the complete course snapshot persists');
    assert.equal(await page.locator('.course .total').innerText(), drafted);
    await page.click('.course-main');
    const downloading = page.waitForEvent('download');
    await page.click('text=Exportera GPX');
    const download = await downloading;
    assert.equal(download.suggestedFilename(), 'testbana.gpx');
    const xml = readFileSync(await download.path(), 'utf8');
    assert.equal((xml.match(/<trkseg>/g) ?? []).length, 2);
    await page.clock.fastForward(6001);
    await page.click('text=Markera som genomförd');
    await page.click('.modal button.primary');
    await page.waitForSelector('.status-Completed');
    assert.equal((await readStored(page, 'courses'))[0].status, 'Completed');
    await page.click('text=Karta');
    await page.waitForSelector('.list button');
    assert.equal(await page.locator('.list .dot-Completed').count(), 0, 'completed lines are hidden by default');
    await page.getByRole('button', { name: 'Dölj genomförda', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('.list .dot-Completed').length === 2);
    assert.equal(await page.locator('.list .dot-Completed').count(), 2);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    checkErrors();
    await context.close();
    console.log(`ok  ${name}: totals, snapshots, GPX, completion and list visibility`);
  }
} finally { await browser.close(); }
